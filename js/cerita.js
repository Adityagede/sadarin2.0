        const related = stories[relatedSlug];
        const article = document.createElement("article");
        article.className = "related-story";

        const link = document.createElement("a");
        link.className = "related-story__link";
        link.href = `cerita.html?artikel=${relatedSlug}`;
        link.setAttribute("aria-label", `Baca: ${related.title}`);

        const figure = document.createElement("figure");
        figure.className = "related-story__media";
        const thumbnail = document.createElement("img");
        thumbnail.src = related.image;
        thumbnail.alt = "";
        thumbnail.loading = "lazy";
        thumbnail.decoding = "async";
        figure.append(thumbnail);

        const copy = document.createElement("div");
        const category = document.createElement("span");
