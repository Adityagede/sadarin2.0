  const params = new URLSearchParams(window.location.search);
  const requestedSlug = params.get("artikel");
  const slug = Object.hasOwn(stories, requestedSlug) ? requestedSlug : storyOrder[0];
  const story = stories[slug];

  const setText = (selector, value) => {
    const element = document.querySelector(selector);
    if (element) element.textContent = value;
  };

  setText("[data-story-category]", story.category);
  setText("[data-story-breadcrumb]", story.title);
  setText("[data-story-title]", story.title);
  setText("[data-story-intro]", story.intro);
  setText("[data-story-summary]", story.summary);

